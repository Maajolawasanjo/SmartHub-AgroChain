import "server-only";
import { createHash } from "node:crypto";
import {
  evaluateRecoveryReviewPreconditions,
  type RecoveryReview,
} from "./privileged-recovery-review";

/**
 * R01.3D.3F — a PURE, NON-EXECUTABLE recovery-ceremony preflight.
 *
 * Inputs represent hypothetical snapshots of a FUTURE authoritative,
 * transactionally locked and versioned recovery ledger. Browser fields,
 * unverified emails, user_metadata or raw client submissions must never be
 * accepted as this evidence. No current service calls this to reset factors.
 *
 * Digest chaining catches accidental changes to a snapshot, but does not
 * provide an independently anchored or signed immutable audit log. The
 * actual event store, officer designation, Auth session check, idempotency
 * nonce consumption, revocation and provider action do not exist yet.
 */
export type RecoveryCeremonyEventType =
  | "REQUESTED"
  | "IDENTITY_REVERIFIED"
  | "OFFICER_APPROVED"
  | "OFFICER_REJECTED"
  | "CANCELLED";

export type RecoveryCeremonyEvent = Readonly<{
  id: string;
  requestId: string;
  subjectAccountId: string;
  actorAccountId: string;
  requestVersion: number;
  sequence: number;
  occurredAtMs: number;
  type: RecoveryCeremonyEventType;
  previousDigest: string;
  digest: string;
}>;

export type RecoveryOfficerSnapshot = Readonly<{
  accountId: string;
  role: "SUPER_ADMIN" | "OPERATIONS" | "OTHER";
  status: "ACTIVE" | "SUSPENDED" | "DISABLED";
  separatelyDesignated: boolean;
  verifiedProviderIdentityMatchesAccount: boolean;
  aal2VerifiedTotp: boolean;
  providerCheckedAtMs: number;
  approvedRequestVersion: number;
}>;

export type RecoveryCeremonySnapshot = Readonly<{
  review: RecoveryReview;
  expectedRequestVersion: number;
  lockedRequestVersion: number;
  nonceDigest: string;
  consumedNonceDigests: readonly string[];
  auditLedgerWritable: boolean;
  authProviderVerified: boolean;
  events: readonly RecoveryCeremonyEvent[];
  officers: readonly RecoveryOfficerSnapshot[];
}>;

export type RecoveryCeremonyResult = Readonly<{
  kind: "NON_EXECUTABLE_RECOVERY_PREFLIGHT";
  candidateForIndependentReview: boolean;
  executable: false;
  reason:
    | "HUMAN_REVIEW_INCOMPLETE"
    | "VERSION_MISMATCH"
    | "REPLAY_OR_MISSING_NONCE"
    | "LEDGER_INTEGRITY_FAILED"
    | "MISSING_ACTIVE_OFFICER_PROOF"
    | "PROVIDER_OR_AUDIT_UNAVAILABLE"
    | "TWO_OFFICER_EVIDENCE_OBSERVED";
}>;

const hexDigest = /^[a-f0-9]{64}$/;
const nonEmpty = (value: unknown): value is string =>
  typeof value === "string" && value.length > 0 && value.length <= 200;

export function recoveryEventDigest(event: Omit<RecoveryCeremonyEvent, "digest">): string {
  // The fixed field order and separator avoid ambiguous hashing from JSON
  // property order. Event IDs and actions must be generated by the server.
  const values = [
    event.id, event.requestId, event.subjectAccountId, event.actorAccountId,
    String(event.requestVersion), String(event.sequence),
    String(event.occurredAtMs), event.type, event.previousDigest,
  ];
  return createHash("sha256").update(values.join("\u001f")).digest("hex");
}

export function inspectRecoveryCeremony(snapshot: RecoveryCeremonySnapshot): RecoveryCeremonyResult {
  const decision = (
    reason: RecoveryCeremonyResult["reason"],
    candidateForIndependentReview = false,
  ): RecoveryCeremonyResult => ({
    kind: "NON_EXECUTABLE_RECOVERY_PREFLIGHT",
    candidateForIndependentReview,
    executable: false,
    reason,
  });

  if (!snapshot || !snapshot.review ||
      !evaluateRecoveryReviewPreconditions(snapshot.review).candidateForApprovedWorkflow)
    return decision("HUMAN_REVIEW_INCOMPLETE");

  if (!Number.isSafeInteger(snapshot.expectedRequestVersion) ||
      snapshot.expectedRequestVersion < 1 ||
      snapshot.lockedRequestVersion !== snapshot.expectedRequestVersion)
    return decision("VERSION_MISMATCH");

  if (!hexDigest.test(snapshot.nonceDigest ?? "") ||
      !Array.isArray(snapshot.consumedNonceDigests) ||
      snapshot.consumedNonceDigests.includes(snapshot.nonceDigest))
    return decision("REPLAY_OR_MISSING_NONCE");

  const { review, events } = snapshot;
  if (!Array.isArray(events) || events.length < 4 || events.length > 100)
    return decision("LEDGER_INTEGRITY_FAILED");

  const seenIds = new Set<string>();
  let previousDigest = "0".repeat(64);
  let previousTime = review.issuedAtMs;
  for (const [index, event] of events.entries()) {
    if (!event || !nonEmpty(event.id) || !nonEmpty(event.requestId) ||
        !nonEmpty(event.subjectAccountId) || !nonEmpty(event.actorAccountId) ||
        seenIds.has(event.id) ||
        event.requestId !== review.requestId ||
        event.subjectAccountId !== review.subjectAccountId ||
        event.requestVersion !== snapshot.expectedRequestVersion ||
        event.sequence !== index + 1 ||
        !Number.isSafeInteger(event.occurredAtMs) ||
        event.occurredAtMs < previousTime ||
        event.occurredAtMs > review.currentTimeMs ||
        event.previousDigest !== previousDigest ||
        !hexDigest.test(event.digest ?? "") ||
        !hexDigest.test(event.previousDigest ?? "") ||
        event.digest !== recoveryEventDigest(event))
      return decision("LEDGER_INTEGRITY_FAILED");
    seenIds.add(event.id);
    previousDigest = event.digest;
    previousTime = event.occurredAtMs;
  }

  const requested = events.filter(event => event.type === "REQUESTED");
  const reverified = events.filter(event => event.type === "IDENTITY_REVERIFIED");
  const approved = events.filter(event => event.type === "OFFICER_APPROVED");
  if (requested.length !== 1 || requested[0] !== events[0] ||
      requested[0].actorAccountId !== review.requestedById ||
      reverified.length !== 1 || approved.length !== 2 ||
      events.length !== 4 ||
      events.some(event => event.type === "OFFICER_REJECTED" ||
        event.type === "CANCELLED") ||
      reverified[0].actorAccountId === review.subjectAccountId ||
      reverified[0].actorAccountId === review.requestedById)
    return decision("LEDGER_INTEGRITY_FAILED");

  if (!Array.isArray(snapshot.officers) || snapshot.officers.length < 2)
    return decision("MISSING_ACTIVE_OFFICER_PROOF");

  const approverIds = new Set<string>();
  for (const event of approved) {
    const officer = snapshot.officers.find(item => item.accountId === event.actorAccountId);
    const decisionRecord = review.approvals.find(item =>
      item.approverAccountId === event.actorAccountId &&
      item.decision === "APPROVE" &&
      item.decisionAtMs === event.occurredAtMs);
    if (!officer || !decisionRecord ||
        approverIds.has(event.actorAccountId) ||
        officer.accountId === review.subjectAccountId ||
        officer.accountId === review.requestedById ||
        officer.role !== "SUPER_ADMIN" ||
        officer.status !== "ACTIVE" ||
        !officer.separatelyDesignated ||
        !officer.verifiedProviderIdentityMatchesAccount ||
        !officer.aal2VerifiedTotp ||
        !Number.isSafeInteger(officer.providerCheckedAtMs) ||
        officer.providerCheckedAtMs > review.currentTimeMs ||
        review.currentTimeMs - officer.providerCheckedAtMs > 5 * 60_000 ||
        officer.approvedRequestVersion !== snapshot.expectedRequestVersion)
      return decision("MISSING_ACTIVE_OFFICER_PROOF");
    approverIds.add(event.actorAccountId);
  }

  if (approverIds.size !== 2 ||
      review.approvals.some(item =>
        item.decision !== "APPROVE" || !approverIds.has(item.approverAccountId)))
    return decision("MISSING_ACTIVE_OFFICER_PROOF");

  if (snapshot.auditLedgerWritable !== true ||
      snapshot.authProviderVerified !== true)
    return decision("PROVIDER_OR_AUDIT_UNAVAILABLE");

  // This is NOT authorization to change Auth state. In an approved future
  // execution path, the nonce must be atomically consumed before any provider
  // action, approvals re-checked against live sessions, and Auth revocation
  // plus compensating audit applied under independently approved controls.
  return decision("TWO_OFFICER_EVIDENCE_OBSERVED", true);
}
